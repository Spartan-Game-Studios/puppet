/**
 * Strings for the library area (see ../catalogs.ts): HOME's cards, imports and
 * prompts (src/app/home.ts, homeView.ts), MODEL INFO and the licence texts
 * (src/library/vrmMeta.ts). Keys are prefixed 'library.'.
 *
 * Licence badge ids (AUTHOR ONLY, CC0...) and the VRM metadata values stay
 * English in code and storage; only the labels below are shown.
 *
 * Plurals: a counted string has one key per CLDR category, `<base>_one`,
 * `_few`, `_many`, `_other`, and pluralKey() picks one with Intl.PluralRules.
 * English and Spanish use one/other (Spanish `many` is for millions, same as
 * other), Russian one/few/many (`other` is fractions: the few form), Chinese
 * has no plural (all four the same).
 */
import type { Tr } from '../types';

const CATEGORIES = ['one', 'few', 'many', 'other'] as const;

/** `library.ago.days` + 5 in ru -> `library.ago.days_many`. */
export function pluralKey<B extends string>(base: B, n: number, locale: string): `${B}_${(typeof CATEGORIES)[number]}` {
  const c = new Intl.PluralRules(locale).select(n) as (typeof CATEGORIES)[number];
  return `${base}_${(CATEGORIES as readonly string[]).includes(c) ? c : 'other'}` as `${B}_${(typeof CATEGORIES)[number]}`;
}

